"""Data pipeline: packed text, synthetic grounded vision, and tool-use SFT.

The synthetic shapes corpus is deliberately small and fully generated by this
repo. It proves the image path learns, but it is not a claim of real-world
visual understanding. Real photographic data is added through the documented
dataset registry with licence and provenance checks.
"""
from __future__ import annotations

import json
import math
import random
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable, Iterator, Sequence

import numpy as np
import torch
from torch.utils.data import Dataset

from .tokenizer import BOS, EOS, PAD, Tokenizer

COLORS = {
    "red": (0.85, 0.15, 0.15),
    "green": (0.15, 0.75, 0.25),
    "blue": (0.15, 0.35, 0.85),
    "yellow": (0.95, 0.85, 0.15),
    "purple": (0.55, 0.2, 0.75),
    "orange": (0.95, 0.55, 0.1),
}
SHAPES = ("circle", "square", "triangle")


class PackedTextDataset(Dataset):
    """Documents tokenized and packed into fixed blocks for next-token training."""

    def __init__(self, token_ids: Sequence[int], block_size: int) -> None:
        if block_size < 2:
            raise ValueError("block_size must be >= 2")
        self.block_size = block_size
        usable = (len(token_ids) // block_size) * block_size
        self.tokens = list(token_ids[:usable])

    def __len__(self) -> int:
        return max(0, len(self.tokens) // self.block_size)

    def __getitem__(self, index: int) -> tuple[torch.Tensor, torch.Tensor]:
        start = index * self.block_size
        chunk = self.tokens[start: start + self.block_size]
        # The chunk includes the next-token target; the input is one shorter.
        # The caller passes seq_len + 1 as block_size, so x and y are seq_len.
        x = torch.tensor(chunk[:-1], dtype=torch.long)
        y = torch.tensor(chunk[1:], dtype=torch.long)
        return x, y


def tokenize_to_shard(
    texts: Iterable[str],
    tokenizer: Tokenizer,
    path: str | Path,
    *,
    dtype: str = "uint32",
    eos_id: int | None = None,
    flush_tokens: int = 1_000_000,
) -> int:
    """Tokenize a document stream into a flat binary shard.

    This is the format used for real training runs: a contiguous array of token
    IDs, read with ``numpy.memmap`` so a 2B-token corpus does not need 16 GB of
    Python integers in RAM. Documents are separated by EOS.
    """
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    end_id = tokenizer.id_of("<|eos|>") if eos_id is None else eos_id
    buffer: list[int] = []
    total = 0
    with path.open("wb") as handle:
        for text in texts:
            buffer.extend(tokenizer.encode(text))
            buffer.append(end_id)
            if len(buffer) >= flush_tokens:
                np.asarray(buffer, dtype=np.dtype(dtype)).tofile(handle)
                total += len(buffer)
                buffer.clear()
        if buffer:
            np.asarray(buffer, dtype=np.dtype(dtype)).tofile(handle)
            total += len(buffer)
    return total


class MemmapTokenDataset(Dataset):
    """Fixed-length blocks over a flat token shard."""

    def __init__(self, path: str | Path, block_size: int, dtype: str = "uint32") -> None:
        if block_size < 1:
            raise ValueError("block_size must be positive")
        self.path = Path(path)
        self.block_size = block_size
        self.dtype = np.dtype(dtype)
        self._array = np.memmap(self.path, dtype=self.dtype, mode="r")
        self._blocks = max(0, (len(self._array) - 1) // block_size)

    def __len__(self) -> int:
        return self._blocks

    def __getitem__(self, index: int) -> tuple[torch.Tensor, torch.Tensor]:
        if index < 0 or index >= self._blocks:
            raise IndexError(index)
        start = index * self.block_size
        chunk = np.asarray(self._array[start: start + self.block_size + 1], dtype=np.int64)
        x = torch.from_numpy(chunk[:-1].copy())
        y = torch.from_numpy(chunk[1:].copy())
        return x, y


class ChatSFTDataset(Dataset):
    """Supervised fine-tuning on chat/tool traces.

    Loss is applied only to assistant tokens (prompt and tool-result tokens are
    masked with -100), so the model learns to answer and call tools rather than
    to reproduce the system prompt.
    """

    def __init__(self, records: Sequence[dict], tokenizer: Tokenizer, block_size: int) -> None:
        self.samples: list[tuple[torch.Tensor, torch.Tensor]] = []
        for record in records:
            messages = record.get("messages", [])
            tools = record.get("tools", [])
            ids = tokenizer.apply_chat_template(messages, tools=tools, add_generation_prompt=False)
            labels = list(ids)
            # Mask everything up to and including each assistant marker; unmask
            # the assistant content and its terminating <|end|>.
            in_assistant = False
            for i, token in enumerate(ids):
                if token == tokenizer.id_of("<|assistant|>"):
                    in_assistant = True
                    labels[i] = -100
                    continue
                if in_assistant and token == tokenizer.id_of("<|end|>"):
                    labels[i] = token
                    in_assistant = False
                    continue
                if not in_assistant:
                    labels[i] = -100
            # model.forward predicts token t+1 at position t, so the supervised
            # target at position t must be the NEXT token (ids[t+1]).  Shift the
            # masked labels left by one; without this the model was asked to
            # predict the token it was already given, so sft_ce went to zero while
            # no tool-call behaviour was actually learned.
            labels = labels[1:] + [-100]
            if len(ids) < 2:
                continue
            if len(ids) > block_size:
                # Keep the tail: SFT is response-focused, and the assistant
                # span is at the end of each turn. Dropping the head is better
                # than truncating away every supervised token.
                ids = ids[-block_size:]
                labels = labels[-block_size:]
            if all(label == -100 for label in labels):
                continue
            self.samples.append((torch.tensor(ids), torch.tensor(labels)))

    def __len__(self) -> int:
        return len(self.samples)

    def __getitem__(self, index: int) -> tuple[torch.Tensor, torch.Tensor]:
        return self.samples[index]


@dataclass
class ShapeSample:
    image: torch.Tensor
    caption: str


def make_shape_image(color: str, shape: str, size: int = 64, seed: int = 0) -> torch.Tensor:
    """Draw one shape with pure tensor operations (no PIL dependency)."""
    generator = torch.Generator().manual_seed(seed)
    image = torch.rand((3, size, size), generator=generator) * 0.12 + 0.04
    rgb = torch.tensor(COLORS[color], dtype=torch.float32).view(3, 1, 1)
    yy, xx = torch.meshgrid(
        torch.arange(size, dtype=torch.float32), torch.arange(size, dtype=torch.float32),
        indexing="ij",
    )
    cx = size / 2 + (torch.rand(1, generator=generator).item() - 0.5) * size * 0.15
    cy = size / 2 + (torch.rand(1, generator=generator).item() - 0.5) * size * 0.15
    radius = size * 0.28
    if shape == "circle":
        mask = ((xx - cx) ** 2 + (yy - cy) ** 2) <= radius ** 2
    elif shape == "square":
        mask = (xx - cx).abs() <= radius * 0.88
        mask &= (yy - cy).abs() <= radius * 0.88
    elif shape == "triangle":
        # Three half-planes form an upward triangle.
        top = (yy >= cy - radius)
        left = (xx - cx) >= -(yy - (cy - radius)) * 0.9
        right = (xx - cx) <= (yy - (cy - radius)) * 0.9
        mask = top & left & right & (yy <= cy + radius)
    else:
        raise ValueError(f"unknown shape {shape}")
    image = torch.where(mask.unsqueeze(0), rgb.expand_as(image), image)
    return image.clamp(0, 1)


class SyntheticShapes(Dataset):
    def __init__(self, size: int = 64, length: int = 1024, seed: int = 0) -> None:
        self.size = size
        self.length = length
        self.seed = seed

    def __len__(self) -> int:
        return self.length

    def __getitem__(self, index: int) -> ShapeSample:
        rng = random.Random(self.seed + index)
        color = rng.choice(list(COLORS))
        shape = rng.choice(SHAPES)
        image = make_shape_image(color, shape, self.size, seed=self.seed + index)
        return ShapeSample(image=image, caption=f"a {color} {shape}")


def collate_text(batch: Sequence[tuple[torch.Tensor, torch.Tensor]], pad_id: int = PAD):
    max_len = max(x.shape[0] for x, _ in batch)
    xs, ys = [], []
    for x, y in batch:
        pad = max_len - x.shape[0]
        xs.append(torch.cat((x, torch.full((pad,), pad_id, dtype=torch.long))))
        ys.append(torch.cat((y, torch.full((pad,), -100, dtype=torch.long))))
    return torch.stack(xs), torch.stack(ys)


def collate_multimodal(batch: Sequence[tuple[torch.Tensor, torch.Tensor, torch.Tensor]]):
    max_len = max(x.shape[0] for x, _, _ in batch)
    xs, ys, ims = [], [], []
    for x, y, image in batch:
        pad = max_len - x.shape[0]
        xs.append(torch.cat((x, torch.full((pad,), PAD, dtype=torch.long))))
        ys.append(torch.cat((y, torch.full((pad,), -100, dtype=torch.long))))
        ims.append(image)
    return torch.stack(xs), torch.stack(ys), torch.stack(ims)


class MultimodalCaptionDataset(Dataset):
    def __init__(self, shapes: SyntheticShapes, tokenizer: Tokenizer) -> None:
        self.shapes = shapes
        self.tokenizer = tokenizer

    def __len__(self) -> int:
        return len(self.shapes)

    def __getitem__(self, index: int) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
        sample = self.shapes[index]
        ids = [BOS] + self.tokenizer.encode(sample.caption) + [EOS]
        labels = [-100] + ids[1:]
        return torch.tensor(ids), torch.tensor(labels), sample.image


def read_jsonl(path: str | Path) -> list[dict]:
    records = []
    with Path(path).open("r", encoding="utf-8") as handle:
        for line in handle:
            line = line.strip()
            if line:
                records.append(json.loads(line))
    return records


def write_jsonl(path: str | Path, records: Iterable[dict]) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as handle:
        for record in records:
            handle.write(json.dumps(record, ensure_ascii=False) + "\n")
